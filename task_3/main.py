# Киселёв Артур
n = int(input("Введите число: ")) # Считываем конечное число из консоли
i = 1 # Устанавливаем начальное значение счетчика
while i <= n: # Выполняем цикл, пока счетчик не превысит n
    print(i) # Печатаем текущее значение счетчика
    i += 1 # Увеличиваем значение i на единицу на каждом шаге